const synthetic=A.preflight(separated).findings.find(f=>f.code==='synthetic_validation');
assert.ok(synthetic);
assert.equal(separated.slice(synthetic.start,synthetic.end),synthetic.evidence);
assert.equal(synthetic.related_evidence.text,'Se utilizarán datos sintéticos.');
assert.equal(A.preflight('Los datos sintéticos permiten una simulación.').findings.filter(f=>f.code==='synthetic_validation').length,0);
